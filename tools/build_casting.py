#!/usr/bin/env python3
"""
Generates composeApp/src/commonMain/kotlin/cz/pfspells/data/CastingTable.kt – spells per day and spells known
(arcanist: spells prepared) of all 27 spellcasting classes, taken from the class tables on Archives of Nethys.

Source: https://aonprd.com/ClassDisplay.aspx?ItemName=<Class> (OGL content, Paizo Community Use Policy)

Usage:  python tools/build_casting.py        (standard library only, ~30 requests, 1 s apart)
"""
import html
import re
import time
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "composeApp/src/commonMain/kotlin/cz/pfspells/data/CastingTable.kt"

# id ve appce → jméno na AoN
CLASSES = {
    "wizard": "Wizard", "sorcerer": "Sorcerer", "arcanist": "Arcanist", "cleric": "Cleric", "oracle": "Oracle",
    "druid": "Druid", "witch": "Witch", "shaman": "Shaman", "psychic": "Psychic", "bard": "Bard", "skald": "Skald",
    "inquisitor": "Inquisitor", "magus": "Magus", "alchemist": "Alchemist", "investigator": "Investigator",
    "summoner": "Summoner", "summoner_unchained": "Summoner (Unchained)", "warpriest": "Warpriest", "hunter": "Hunter",
    "mesmerist": "Mesmerist", "occultist": "Occultist", "spiritualist": "Spiritualist", "paladin": "Paladin",
    "antipaladin": "Antipaladin", "ranger": "Ranger", "bloodrager": "Bloodrager", "medium": "Medium",
}
LV = {"0": 0, "1st": 1, "2nd": 2, "3rd": 3, "4th": 4, "5th": 5, "6th": 6, "7th": 7, "8th": 8, "9th": 9}


def fetch(name: str) -> str:
    url = "https://aonprd.com/ClassDisplay.aspx?ItemName=" + urllib.parse.quote(name)
    req = urllib.request.Request(url, headers={"User-Agent": "pf-spellbook-build"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8")


def rows(table: str):
    # AoN občas vynechá poslední </td> před </tr>
    for tr in re.findall(r"<tr[^>]*>(.*?)</tr>", table, re.S):
        cells = re.findall(r"<t[dh][^>]*>(.*?)(?=</t[dh]>|<t[dh][ >]|$)", tr, re.S)
        yield [html.unescape(re.sub(r"<[^>]+>", "", c)).strip() for c in cells]


def spell_table(table: str):
    """{úroveň classy: {spell level: počet nebo None}} z tabulky s hlavičkou Level … 1st 2nd …, jinak None."""
    rs = list(rows(table))
    for i, r in enumerate(rs):
        cols = [(j, LV[c]) for j, c in enumerate(r) if c in LV]
        if len(cols) < 3 or not r or not r[0].lower().startswith("level"):
            continue
        res = {}
        for row in rs[i + 1:]:
            m = re.match(r"(\d+)(st|nd|rd|th)$", row[0]) if row else None
            if not m:
                continue
            vals = {}
            for j, sl in cols:
                v = re.match(r"\d+", row[j]) if j < len(row) else None
                vals[sl] = int(v.group()) if v else None
            res[int(m.group(1))] = vals
        return res if len(res) == 20 else None
    return None


def encode(t) -> str:
    """Řádky po úrovních classy oddělené |, hodnoty pro spell level 0..max mezerou, - = nemá."""
    top = max(max(r) for r in t.values())
    out = []
    for lvl in range(1, 21):
        r = t[lvl]
        out.append(" ".join("-" if r.get(sl) is None else str(r[sl]) for sl in range(0, top + 1)))
    return "|".join(out)


def main():
    lines = [
        "// GENERATED by tools/build_casting.py from Archives of Nethys class tables (OGL) – do not edit by hand.",
        "package cz.pfspells.data",
        "",
        "/** id classy → (spells per day, spells known / arcanist: spells prepared). Formát viz [parseSlotTable]. */",
        "internal val CASTING_TABLE: Map<String, Pair<String, String?>> = mapOf(",
    ]
    for cid, name in CLASSES.items():
        tables = [t for t in (spell_table(x) for x in re.findall(r"<table.*?</table>", fetch(name), re.S)) if t]
        if not tables:
            raise SystemExit(f"{name}: no spell table")
        per_day = encode(tables[0])
        known = f'"{encode(tables[1])}"' if len(tables) > 1 else "null"
        lines.append(f'    "{cid}" to ("{per_day}" to {known}),')
        print(f"{cid}: {len(tables)} table(s)")
        time.sleep(1)
    lines.append(")")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(CLASSES)} classes")


if __name__ == "__main__":
    main()
