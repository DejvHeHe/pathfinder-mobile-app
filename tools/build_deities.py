#!/usr/bin/env python3
"""
Generates composeApp/src/commonMain/kotlin/cz/pfspells/data/DeityTable.kt – PF1 deities (pantheon, alignment,
areas of concern, domains, favored weapon) for the character deity picker and feat prerequisites
("worshiper of a good deity", "alignment within one step of your deity's").

Source: Archives of Nethys, https://aonprd.com/DeitiesByGroup.aspx (OGL / Paizo Community Use Policy)

Subdomains come from each deity's page (DeityDisplay.aspx, ~460 requests, 1 per second, cached in build/deity-cache).

Usage:  python tools/build_deities.py [DeitiesByGroup.html] [--cache DIR]
        (optional local copy of the list page and a directory with already downloaded deity pages named
         "<url-encoded name>.html", e.g. when Python cannot verify the certificate – download them with curl)
"""
import html
import re
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "composeApp/src/commonMain/kotlin/cz/pfspells/data/DeityTable.kt"
URL = "https://aonprd.com/DeitiesByGroup.aspx"
ALIGNMENTS = {"LG", "NG", "CG", "LN", "N", "CN", "LE", "NE", "CE"}


def fetch(url: str) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "pf-spellbook-build"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read().decode("utf-8", errors="replace")


def subdomains(page: str):
    """„<b>Subdomains</b> <a>Archon (Good)</a>, <a>Caves</a>…<br“ → [„archon“, „caves“] (bez závorek a hvězdiček).
    None = stránka božstva chybí / nejde přečíst (appka pak nabídne všechny subdomény)."""
    m = re.search(r"<b>Subdomains</b>(.*?)<br", page, re.S)
    if not m:
        return [] if "<b>Domains</b>" in page else None
    names = [re.sub(r"\s*\(.*?\)|\*", "", text(a)).strip().lower() for a in re.findall(r"<a[^>]*>(.*?)</a>", m.group(1))]
    return sorted({n for n in names if n})


def deity_page(name: str, cache: Path) -> str:
    f = cache / (urllib.parse.quote(name) + ".html")
    if f.exists() and f.stat().st_size > 0:
        return f.read_text(encoding="utf-8", errors="replace")
    page = fetch("https://aonprd.com/DeityDisplay.aspx?ItemName=" + urllib.parse.quote(name))
    cache.mkdir(parents=True, exist_ok=True)
    f.write_text(page, encoding="utf-8")
    time.sleep(1)
    return page


def text(cell: str) -> str:
    return html.unescape(re.sub(r"<[^>]+>", "", cell)).strip()


def kstr(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def main():
    args = sys.argv[1:]
    cache = ROOT / "build/deity-cache"
    if "--cache" in args:
        i = args.index("--cache")
        cache = Path(args[i + 1])
        del args[i:i + 2]
    page = Path(args[0]).read_text(encoding="utf-8", errors="replace") if args else fetch(URL)
    table = page[page.index("MainContent_GridViewDeities"):]
    table = table[:table.index("</table>")]
    rows = {}
    for tr in re.findall(r"<tr[^>]*>(.*?)</tr>", table, re.S):
        cells = re.findall(r"<td[^>]*>(.*?)</td>", tr, re.S)
        if len(cells) < 6:
            continue
        name = text(cells[0])
        alignment = text(cells[2]).upper()
        domains = [text(d).lower() for d in re.findall(r"<a[^>]*>(.*?)</a>", cells[4])]
        link = re.search(r'DeityDisplay\.aspx\?ItemName=([^"]+)"', cells[0])
        page_name = html.unescape(link.group(1)) if link else name
        row = (name, text(cells[1]), alignment if alignment in ALIGNMENTS else "", text(cells[3]), domains, text(cells[5]), page_name)
        rows.setdefault(name.lower(), row)  # stejné božstvo ve víc panteonech – první výskyt
    lines = [
        "// GENERATED by tools/build_deities.py from Archives of Nethys (DeitiesByGroup.aspx) – do not edit by hand.",
        "package cz.pfspells.data",
        "",
        "internal val DEITY_TABLE: List<DeityInfo> = listOf(",
    ]
    for name, pantheon, alignment, areas, domains, weapon, page_name in sorted(rows.values(), key=lambda r: r[0].lower()):
        al = f"Alignment.{alignment}" if alignment else "null"
        subs = subdomains(deity_page(page_name, cache))
        lines.append(
            f"    DeityInfo({kstr(name)}, {kstr(pantheon)}, {al}, {kstr(areas)}, "
            f"listOf({', '.join(kstr(d) for d in domains)}), {kstr(weapon)}, "
            + (f"subdomains = listOf({', '.join(kstr(s) for s in subs)})" if subs is not None else "subdomains = null") + "),")
    lines.append(")")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(rows)} deities")


if __name__ == "__main__":
    main()
