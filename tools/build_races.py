#!/usr/bin/env python3
"""
Generates composeApp/src/commonMain/kotlin/cz/pfspells/data/RaceTable.kt – playable PF1 races
(size, base speed, racial ability and skill modifiers, class skills, creature type / subtypes) for characters and racial feat prerequisites.

Source: Foundry VTT PF1 system, packs/races (OGL content, GPL-3.0 project)
        https://gitlab.com/foundryvtt_pathfinder1e/foundryvtt-pathfinder1
Groups (core / featured / uncommon) follow the Advanced Race Guide; everything else is "other".

Usage:  pip install pyyaml  &&  python tools/build_races.py [races.zip]
        (optional local ZIP of packs/races, e.g. when Python cannot verify the GitLab certificate)
"""
import io
import sys
import re
import urllib.request
import zipfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "composeApp/src/commonMain/kotlin/cz/pfspells/data/RaceTable.kt"
ZIP = "https://gitlab.com/api/v4/projects/16774935/repository/archive.zip?sha=master&path=packs/races"

SIZE = {"fine": "FINE", "dim": "DIMINUTIVE", "tiny": "TINY", "sm": "SMALL", "med": "MEDIUM",
        "lg": "LARGE", "huge": "HUGE", "grg": "GARGANTUAN", "col": "COLOSSAL"}
ABILITIES = ["str", "dex", "con", "int", "wis", "cha"]
CORE = {"dwarf", "elf", "gnome", "half-elf", "half-orc", "halfling", "human"}
FEATURED = {"aasimar", "catfolk", "dhampir", "drow", "fetchling", "goblin", "hobgoblin", "ifrit", "kobold", "orc",
            "oread", "ratfolk", "sylph", "tengu", "tiefling", "undine"}
UNCOMMON = {"changeling", "duergar", "gillman", "grippli", "kitsune", "merfolk", "nagaji", "samsaran", "strix", "suli",
            "svirfneblin", "vanara", "vishkanya", "wayang"}


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "pf-spellbook-build"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read()


def race_id(name: str) -> str:
    """„Lashunta (Female)“ → „lashunta-female“."""
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def kstr(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    data = Path(sys.argv[1]).read_bytes() if len(sys.argv) > 1 else fetch(ZIP)
    z = zipfile.ZipFile(io.BytesIO(data))
    rows = []
    for n in z.namelist():
        if not n.endswith(".yaml") or n.split("/")[-1].startswith("_"):
            continue
        d = yaml.safe_load(z.read(n))
        s = d.get("system") or {}
        rid = race_id(d["name"])
        mods = {}
        for c in (s.get("changes") or {}).values():
            t = c.get("target")
            if t in ABILITIES and c.get("type") == "racial":
                mods[t] = mods.get(t, 0) + int(str(c.get("formula")).strip())
        # rasové bonusy ke skillům („skill.perception“, „skill.knowledge.planes“, „skill.knowledge“ = všechny)
        skill_mods = {}
        for c in (s.get("changes") or {}).values():
            t = str(c.get("target") or "")
            if t.startswith("skill.") and c.get("type") == "racial":
                k = t[len("skill."):]
                skill_mods[k] = skill_mods.get(k, 0) + int(str(c.get("formula")).strip())
        class_skills = sorted(s.get("classSkills") or [])
        darkvision = max([int(str(c.get("formula")).strip()) for c in (s.get("changes") or {}).values()
                          if c.get("target") == "sensedv"] or [0])
        low_light = "lowLightVision" in (s.get("changeFlags") or [])
        subtypes = sorted({x.strip().lower() for x in (s.get("creatureSubtypes") or []) if x})
        types = s.get("creatureTypes") or []
        group = "CORE" if rid in CORE else "FEATURED" if rid in FEATURED else "UNCOMMON" if rid in UNCOMMON else "OTHER"
        # human, half-elf, half-orc: +2 k jednomu atributu podle volby (Foundry to nemá jako změnu)
        any_bonus = not mods and "human" in subtypes
        rows.append((rid, d["name"], group, SIZE.get(s.get("size"), "MEDIUM"),
                     int((s.get("speeds") or {}).get("land") or 30), mods, any_bonus,
                     (types[0] if types else ""), subtypes, skill_mods, class_skills, darkvision, low_light))
    rows.sort(key=lambda r: r[1])
    lines = [
        "// GENERATED by tools/build_races.py from Foundry VTT PF1 (packs/races, OGL) – do not edit by hand.",
        "package cz.pfspells.data",
        "",
        "internal val RACE_TABLE: List<RaceInfo> = listOf(",
    ]
    for rid, name, group, size, speed, mods, any_bonus, ctype, subtypes, skill_mods, class_skills, darkvision, low_light in rows:
        m = ", ".join(f"Ability.{a.upper()} to {mods[a]}" for a in ABILITIES if a in mods)
        sub = ", ".join(kstr(x) for x in subtypes)
        lines.append(
            f"    RaceInfo({kstr(rid)}, {kstr(name)}, RaceGroup.{group}, CreatureSize.{size}, speed = {speed}, "
            f"mods = mapOf({m}), anyBonus = {'true' if any_bonus else 'false'}, type = {kstr(ctype)}, subtypes = listOf({sub})"
            + (f", skillMods = mapOf({', '.join(kstr(k) + ' to ' + str(v) for k, v in sorted(skill_mods.items()))})" if skill_mods else "")
            + (f", classSkills = setOf({', '.join(kstr(x) for x in class_skills)})" if class_skills else "")
            + (f", darkvision = {darkvision}" if darkvision else "")
            + (", lowLightVision = true" if low_light else "")
            + "),")
    lines.append(")")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(rows)} races")


if __name__ == "__main__":
    main()
